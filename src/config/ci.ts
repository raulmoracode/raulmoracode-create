export function ciWorkflowYaml(): string {
  return [
    "name: CI",
    "",
    "on:",
    "  push:",
    "  pull_request:",
    "",
    "jobs:",
    "  validate:",
    "    runs-on: ubuntu-latest",
    "    steps:",
    "      - uses: actions/checkout@v4",
    "",
    "      - uses: pnpm/action-setup@v4",
    "        with:",
    "          version: 12.6.0",
    "",
    "      - uses: actions/setup-node@v4",
    "        with:",
    "          node-version: 24",
    "          cache: pnpm",
    "",
    "      - run: pnpm install --no-frozen-lockfile",
    "      - run: pnpm check",
    "      - run: pnpm test",
    "      - run: pnpm build",
    "",
  ].join("\n");
}
