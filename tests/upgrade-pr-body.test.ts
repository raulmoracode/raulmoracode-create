describe("escaping and line endings", () => {
  it("escapes pipes and folds newlines in table cells", () => {
    const body = upgradePrBody(
      report({
        notes: [
          {
            version: "1.0.8",
            summary: "s",
            changes: [{ files: ["a|b.ts"], what: "w|1", why: "line1\nline2" }],
          },
        ],
      }),
    );
    expect(body).toContain("| a\\|b.ts | — | — | w\\|1 | line1<br>line2 |");
  });

  it("normalises CRLF before diffing", () => {
    const diff = unifiedDiff("a\r\nb\r\n", "a\nb\n");
    expect(diff).toBe("");
    const body = upgradePrBody(
      report({
        files: [
          {
            path: "x.ts",
            status: "overwritten",
            previousContent: "a\r\nb\r\n",
            nextContent: "a\r\nc\r\n",
          },
        ],
      }),
    );
    expect(body).toContain("-b");
    expect(body).toContain("+c");
    expect(body).not.toContain("\r");
  });
});

describe("unifiedDiff", () => {
  it("returns an empty string when the content is identical", () => {
    expect(unifiedDiff("a\nb\n", "a\nb\n")).toBe("");
    expect(unifiedDiff(null, null)).toBe("");
  });

  it("diffs a single changed line", () => {
    const diff = unifiedDiff("a\nb\nc\n", "a\nB\nc\n");
    expect(diff.split("\n")).toEqual([
      "@@ -1,3 +1,3 @@",
      " a",
      "-b",
      "+B",
      " c",
    ]);
  });

  it("diffs insertions and deletions", () => {
    expect(unifiedDiff("a\nc\n", "a\nb\nc\nd\n")).toBe(
      "@@ -1,2 +1,4 @@\n a\n+b\n c\n+d",
    );
    expect(unifiedDiff("a\nb\nc\n", "a\nc\n")).toBe(
      "@@ -1,3 +1,2 @@\n a\n-b\n c",
    );
  });

  it("counts added and removed lines", () => {
    expect(diffLineCounts("a\nb\n", "a\n")).toEqual({ added: 0, removed: 1 });
    expect(diffLineCounts("a\n", "a\nb\n")).toEqual({ added: 1, removed: 0 });
    expect(diffLineCounts("a\nb\nc\n", "a\nB\nc\n")).toEqual({
      added: 1,
      removed: 1,
    });
    expect(diffCounts("a\nb\nc\n", "a\nB\nc\n")).toBe("+1 −1");
    expect(diffCounts(null, "x\n")).toBe("+1 −0");
    expect(diffCounts("x\n", null)).toBe("+0 −1");
    expect(diffCounts("a\n", "a\n")).toBe("+0 −0");
  });

  it("caps very large files", () => {
    const previous = Array.from(
      { length: MAX_DIFF_LINES + 50 },
      (_, i) => `l${i}`,
    );
    const next = Array.from({ length: MAX_DIFF_LINES + 50 }, (_, i) => `m${i}`);
    const diff = unifiedDiff(
      `${previous.join("\n")}\n`,
      `${next.join("\n")}\n`,
    );
    expect(diff).toContain("diff truncated to the first");
    expect(diff.split("\n").length).toBeLessThanOrEqual(MAX_DIFF_LINES * 2 + 2);
    expect(diff.length).toBeLessThan(MAX_DIFF_CHARS);

    const wide = Array.from(
      { length: 300 },
      (_, i) => `line ${i} ${"x".repeat(200)}`,
    );
    const wideNext = wide.map((line) => `${line} changed`);
    const wideDiff = unifiedDiff(
      `${wide.join("\n")}\n`,
      `${wideNext.join("\n")}\n`,
    );
    expect(wideDiff).toContain("diff truncated (");
    expect(wideDiff.length).toBeLessThan(MAX_DIFF_CHARS + 200);
  });
});

