describe("truncateForGithub", () => {
  function hugeReport(fileCount: number): UpgradeReport {
    const lines = Array.from(
      { length: 200 },
      (_, i) => `line ${i} ${"y".repeat(60)}`,
    );
    return report({
      files: Array.from({ length: fileCount }, (_, index) => ({
        path: `file-${index}.json`,
        status: "overwritten" as const,
        previousContent: `${lines.join("\n")}\n`,
        nextContent: `${lines.map((line) => `${line} changed`).join("\n")}\n`,
      })),
      notes: [
        {
          version: "1.0.8",
          summary: "s",
          changes: [
            {
              files: Array.from(
                { length: fileCount },
                (_, index) => `file-${index}.json`,
              ),
              what: "Regenerated",
              why: "New template",
            },
          ],
        },
      ],
    });
  }

  it("keeps short bodies untouched", () => {
    const body = upgradePrBody(report());
    expect(truncateForGithub(body)).toBe(body);
  });

  it("trims diffs and keeps summary, warning section, tables and action items", () => {
    const body = upgradePrBody(hugeReport(60));
    expect(body.length).toBeGreaterThan(GITHUB_PR_BODY_LIMIT);
    const truncated = truncateForGithub(body);
    expect(truncated.length).toBeLessThanOrEqual(GITHUB_PR_BODY_LIMIT);
    expect(truncated).toContain("## Summary");
    expect(truncated).toContain("## ⚠️ Overwritten files with local changes");
    expect(truncated).toContain("| File | Status | +/− lines | What | Why |");
    expect(truncated).toContain("## Dependencies");
    expect(truncated).toContain("## Action items");
    expect(truncated).toContain("| Count | Value |");
    expect(truncated).toContain("Some inline diffs were trimmed");
    expect(truncated).toContain("**Files changed** tab");
    expect(truncated).not.toContain("```diff");
  });

  it("is idempotent", () => {
    const body = upgradePrBody(hugeReport(60));
    const once = truncateForGithub(body);
    expect(truncateForGithub(once)).toBe(once);
    expect(truncateForGithub(truncateForGithub(once))).toBe(once);
  });

  it("collapses before dropping diffs", () => {
    const body = upgradePrBody(hugeReport(12));
    expect(body.length).toBeGreaterThan(GITHUB_PR_BODY_LIMIT);
    const collapsed = truncateForGithub(body);
    expect(collapsed.length).toBeLessThanOrEqual(GITHUB_PR_BODY_LIMIT);
    expect(collapsed).not.toContain("```diff");
  });

  it("appends the note when the anchor is missing", () => {
    const long = `${"x".repeat(GITHUB_PR_BODY_LIMIT)}\n\nend`;
    const truncated = truncateForGithub(long);
    expect(truncated).toContain("Some inline diffs were trimmed");
    expect(truncateForGithub(truncated)).toBe(truncated);
  });
});
